import fs from 'node:fs';
const bytes = fs.readFileSync('app/public/models/production-room-full.glb');
const jsonLength = bytes.readUInt32LE(12);
const json = JSON.parse(bytes.subarray(20,20+jsonLength).toString('utf8').replace(/\0+$/,'').trim());
const binHeader = 20 + jsonLength;
const binLength = bytes.readUInt32LE(binHeader);
const binStart = binHeader + 8;
const node = json.nodes.find((entry) => entry.name === 'hex_panel_1');
const primitive = json.meshes[node.mesh].primitives[0];
const accessor = json.accessors[primitive.attributes.POSITION];
const view = json.bufferViews[accessor.bufferView];
const start = binStart + (view.byteOffset ?? 0) + (accessor.byteOffset ?? 0);
const stride = view.byteStride ?? 12;
const values = [];
for (let i=0;i<accessor.count;i++) values.push([0,1,2].map((axis) => Number(bytes.readFloatLE(start+i*stride+axis*4).toFixed(4))));
const unique = [...new Map(values.map((v)=>[v.join(','),v])).values()];
const result = { node: node.name, mesh: json.meshes[node.mesh].name, accessor: {count:accessor.count,type:accessor.type,min:accessor.min,max:accessor.max}, primitive: {mode:primitive.mode,indices:primitive.indices,indexCount:json.accessors[primitive.indices]?.count}, uniquePositionCount:unique.length, uniquePositions:unique };
fs.writeFileSync('deliveries/G7/preparation/maker-evidence/pre-g7-12/attempt-17/hex-mesh-inspection.json',JSON.stringify(result,null,2)+'\n');
