#!/usr/bin/env python3
"""Run the pinned FINISH-50 patch build and replay, preserving a raw transcript."""
from __future__ import annotations
import json
import subprocess
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
REPO = PACKAGE.parents[1]


def capture(label: str, argv: list[str], cwd: Path) -> tuple[str, int]:
    p = subprocess.run(argv, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    # Preserve captured content while making the transcript's line boundaries
    # readable and stable across Windows and Unix subprocesses.
    out = p.stdout.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    err = p.stderr.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
    block = [
        f"## {label}",
        f"cwd: {cwd}",
        f"argv: {json.dumps(argv, ensure_ascii=False)}",
        f"exitCode: {p.returncode}",
        "--- stdout ---",
        out.rstrip("\r\n") if out else "(empty)",
        "--- stderr ---",
        err.rstrip("\r\n") if err else "(empty)",
        "",
    ]
    return "\n".join(block), p.returncode


def main() -> int:
    python = sys.executable
    checks = [
        ("Python version", [python, "--version"], REPO),
        ("Git version", ["git", "--version"], REPO),
        ("Build binary source.patch", [python, "scripts/build-source-patch.py", "--repo", str(REPO)], PACKAGE),
        ("Verify raw Git bindings and replay source.patch", [python, "scripts/replay-source-patch.py", "--repo", str(REPO)], PACKAGE),
    ]
    blocks: list[str] = [
        "FINISH-50 B1-R8 RAW COMMAND TRANSCRIPT",
        "Generated by scripts/run-finish50-checks.py; stdout/stderr are captured exactly except UTF-8 decoding and line-ending normalization to LF.",
        "",
    ]
    failed = False
    for label, argv, cwd in checks:
        block, code = capture(label, argv, cwd)
        blocks.append(block)
        failed |= code != 0
    transcript = "\n".join(blocks)
    (PACKAGE / "commands.log").write_text(transcript, encoding="utf-8", newline="\n")
    print(transcript)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
